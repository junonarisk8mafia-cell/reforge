var EZKEY="reforge_easy";
var on=false;
try{on=localStorage.getItem(EZKEY)==="1";}catch(e){}

var orig=[];   /* もとの HTML を おぼえて おく */

function buildEZ(i){
  var e=EZ[i]; if(!e)return null;
  return '<div class="sosdo"><b>🔥 やること</b><br>'+e[1]+'</div>'+
         '<div class="soslaw"><b>⚖ たいせつな こと</b><br>'+e[2]+'</div>'+
         (e[3]?'<div class="soswarn"><b>⚠ きを つけて</b><br>'+e[3]+'</div>':'');
}

function apply(){
  var items=document.querySelectorAll("#view-sos .sositem");
  items.forEach(function(it,i){
    var bd=it.querySelector(".bd");
    var hd=it.querySelector(".hd span:nth-child(2)");
    if(!bd)return;
    if(!orig[i])orig[i]={bd:bd.innerHTML,hd:hd?hd.textContent:""};
    if(on){
      var h=buildEZ(i);
      if(h){bd.innerHTML=h; if(hd&&EZ[i])hd.textContent=EZ[i][0];}
    }else{
      bd.innerHTML=orig[i].bd;
      if(hd)hd.textContent=orig[i].hd;
    }
  });
  document.body.classList.toggle("ez",on);
  var sw=document.getElementById("ezsw");
  if(sw){sw.classList.toggle("on",on); sw.textContent = on ? "ON" : "OFF";}
}

/* ボタンを SOS がめんの うえに つける */
function mount(){
  var v=document.getElementById("view-sos");
  if(!v)return;
  var bar=document.createElement("div");
  bar.className="ezbar";
  bar.innerHTML='<div class="lb"><b>やさしい 日本語</b><br>みじかい ぶんしょうに かえます。<span style="color:#8fbf7f">Easy Japanese</span></div>'+
                '<button class="ezsw" id="ezsw">OFF</button>';
  v.insertBefore(bar, v.children[1] || null);
  document.getElementById("ezsw").addEventListener("click",function(){
    on=!on;
    try{localStorage.setItem(EZKEY,on?"1":"0");}catch(e){}
    apply();
    window.scrollTo(0,0);
  });
  apply();
}

if(document.getElementById("view-sos")){mount();}
else{setTimeout(mount,300);}

